import assert from "node:assert/strict";
const g: any = globalThis;
g.self = g;
const log: any[] = [];
g.postMessage = (m: any) => log.push(m);
await import("../src/sim/worker");
const send = (m: any) => g.onmessage({ data: m });
const wait = (ms: number) => new Promise((r) => setTimeout(r, ms));
send({ t: "init", agents: 6 });
await wait(2500);
const count = (t: string) => log.filter((m) => m.t === t).length;
console.log("ready", count("ready"), "frames", count("frame"), "snaps", count("snap"), "profile", count("profile"));
const f = log.filter((m) => m.t === "frame").pop();
console.log("frame n", f.n, "tr len", f.tr.length, "look", Array.from(f.look).join(","), "NaN?", Array.from(f.tr as Float32Array).some((v) => Number.isNaN(v)));
send({ t: "speed", v: 100 }); await wait(2500);
const snap = log.filter((m) => m.t === "snap").pop().snap;
console.log("x100 effSpeed", snap.effSpeed.toFixed(1), "gen", snap.gen, "stage", snap.stage.label, "assist", snap.assist);
send({ t: "push" }); send({ t: "mode", mode: "manual" }); send({ t: "manual", u: new Array(19).fill(0.3) }); send({ t: "speed", v: 1 }); await wait(1200);
send({ t: "push" }); send({ t: "resetSlot", i: 0 });
send({ t: "mode", mode: "test" }); await wait(800);
send({ t: "unlockAll", v: true }); send({ t: "terrain", i: 2 }); send({ t: "mode", mode: "train" }); send({ t: "agents", n: 4 }); send({ t: "speed", v: 20 }); await wait(2000);
send({ t: "export", purpose: "x" }); await wait(100);
const b = log.find((m) => m.t === "brain");
assert(b?.data?.tasks?.walk?.mean?.length === b?.data?.genomeSize);
console.log("brain", b.data.genomeSize, b.data.tasks.walk.mean.length);
send({ t: "import", data: b.data }); await wait(300);
send({ t: "import", data: { format: "x" } }); await wait(100);
console.log("toasts", log.filter((m) => m.t === "toast").map((m) => m.text));
const s2 = log.filter((m) => m.t === "snap").pop().snap;
assert(count("ready") > 0 && count("frame") > 0 && count("snap") > 0);
assert(log.some(m => m.t === "toast" && m.text.includes("v2 cargado")));
send({ t: "task", task: "boxing" }); await wait(500);
const boxingProfile = log.filter(m => m.t === "profile").pop();
assert.equal(boxingProfile.task, "boxing");
assert(boxingProfile.bag);
const boxingFrame = log.filter(m => m.t === "frame").pop();
assert(boxingFrame.props.some((v: number) => v !== 0));
console.log("final", s2.mode, "terrain", s2.terrainIdx, "slots", s2.slotCount, "gen", s2.gen);
process.exit(0);
