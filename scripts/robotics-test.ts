import assert from "node:assert/strict";
import { RobotController, generationDomain } from "../src/sim/robotics";
import { N_JOINTS } from "../src/sim/spec";
import { Simulation } from "../src/sim/sim";

const controller = new RobotController();
const actions = new Float32Array(N_JOINTS).fill(1);
controller.apply(actions, {upX: 0, wz: 0}, 1 / 30, true);
assert(actions.every(v => v >= -1 && v <= 1 && Math.abs(v) <= 5 / 30 + 1e-6));
controller.reset();
actions.fill(NaN);
controller.apply(actions, {upX: 0, wz: 0}, 1 / 30, true);
assert(actions.every(Number.isFinite));
const domain = generationDomain(5, 0, 0.2);
assert.deepEqual(domain, generationDomain(5, 0, 0.2));
assert(domain.gravity >= 0.8 && domain.gravity <= 1.2);
assert(domain.friction >= 0.8 && domain.friction <= 1.2);
assert.deepEqual(generationDomain(5, 0, 0), {gravity: 1, friction: 1});

const sim = await Simulation.create(123);
sim.desiredSlots = 4;
sim.configure("train");
sim.setRobotics(true, 0.2);
assert(sim.slots.every(s => s.domain.gravity === sim.slots[0].domain.gravity && s.domain.friction === sim.slots[0].domain.friction));
assert(Math.abs(sim.slots[0].world.gravity.y - sim.slots[0].agent.gravity) < 1e-5);
for (let i = 0; i < 300; i++) sim.stepOnce();
assert(sim.slots.every(s => s.agent.bodies.every(b => Number.isFinite(b.translation().y))));
const saved = JSON.parse(JSON.stringify(sim.exportBrain()));
const restored = await Simulation.create(7);
restored.desiredSlots = 2;
restored.configure("train");
restored.importBrain(saved);
assert.equal(restored.robotController, true);
assert.equal(restored.domainRandomization, 0.2);
assert.deepEqual(restored.slots[0].domain, sim.slots[0].domain);
restored.configure("test");
assert.deepEqual(restored.slots[0].domain, {gravity: 1, friction: 1});
delete saved.robotics;
restored.importBrain(saved);
assert.equal(restored.robotController, false, "guardados antiguos no cambian de controlador");
sim.slots.forEach(s => s.dispose());
restored.slots.forEach(s => s.dispose());
console.log("Control limitado, variación común y compatibilidad: OK");
